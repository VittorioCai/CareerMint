/**
 * Copies the onnxruntime WebAssembly runtime out of node_modules and into
 * public/ocr/wasm so the browser fetches it from our own origin instead of a
 * third-party CDN.
 *
 * The model weights next to it in public/ocr/models are committed: they come
 * from Baidu object storage, which is slow from Europe and unreachable from
 * some networks, and the observed failure mode is a hang rather than an error.
 * The runtime is copied rather than committed because it is 26 MB and already
 * pinned by the lockfile.
 *
 * Runs on postinstall so `next dev`, `next build` and CI all get the same
 * assets without a network call.
 */
import { createRequire } from "node:module";
import {
  copyFile,
  mkdir,
  readdir,
  readFile,
  rm,
  stat,
  writeFile,
} from "node:fs/promises";
import { dirname, join, resolve } from "node:path";

const RUNTIME_FILES = [
  "ort-wasm-simd-threaded.jsep.wasm",
  "ort-wasm-simd-threaded.jsep.mjs",
];
const MODEL_FILES = [
  "PP-OCRv6_tiny_det_onnx_infer.tar",
  "PP-OCRv6_tiny_rec_onnx_infer.tar",
];

const require = createRequire(import.meta.url);
const projectRoot = resolve(dirname(new URL(import.meta.url).pathname), "..");

// The runtime goes under its own version, because the filename does not carry
// one: `ort-wasm-simd-threaded.jsep.wasm` is the same string in every release.
// Without the version in the path, caching it immutably would pin a stale
// runtime on every returning user after an upgrade — and not caching it costs
// 6 MB (gzipped) on every session that touches a scanned PDF.
// The package does not export ./package.json, so read it next to a file it
// does export rather than reaching into node_modules by guesswork.
const runtimeVersion = JSON.parse(
  await readFile(
    join(
      dirname(require.resolve("onnxruntime-web/ort-wasm-simd-threaded.jsep.wasm")),
      "..",
      "package.json",
    ),
    "utf8",
  ),
).version;
const wasmRoot = join(projectRoot, "public", "ocr", "wasm");
const wasmTarget = join(wasmRoot, runtimeVersion);
const modelTarget = join(projectRoot, "public", "ocr", "models");
const versionModule = join(
  projectRoot,
  "src",
  "features",
  "source-assets",
  "ocr",
  "runtime-version.ts",
);

async function exists(path) {
  try {
    await stat(path);
    return true;
  } catch {
    return false;
  }
}

async function copyRuntime() {
  // Old versions are dead weight in the deployment and confusing on disk.
  if (await exists(wasmRoot)) {
    for (const entry of await readdir(wasmRoot)) {
      if (entry !== runtimeVersion) {
        await rm(join(wasmRoot, entry), { recursive: true, force: true });
      }
    }
  }
  await mkdir(wasmTarget, { recursive: true });
  for (const file of RUNTIME_FILES) {
    let from;
    try {
      // onnxruntime-web exports each runtime file as its own subpath, so this
      // fails loudly if a version bump renames or drops one.
      from = require.resolve(`onnxruntime-web/${file}`);
    } catch {
      throw new Error(
        `sync-ocr-assets: onnxruntime-web no longer exports ${file}. ` +
          "Update RUNTIME_FILES and re-run `pnpm test:e2e:real-ocr`.",
      );
    }
    if (!(await exists(from))) {
      throw new Error(`sync-ocr-assets: ${file} resolved but is missing on disk.`);
    }
    await copyFile(from, join(wasmTarget, file));
  }
}

async function verifyModels() {
  const present = (await exists(modelTarget))
    ? new Set(await readdir(modelTarget))
    : new Set();
  const missing = MODEL_FILES.filter((file) => !present.has(file));
  if (missing.length > 0) {
    throw new Error(
      `sync-ocr-assets: missing committed OCR models: ${missing.join(", ")}. ` +
        "They are served from public/ocr/models so no user request reaches a " +
        "third-party CDN; re-add them before building.",
    );
  }
}

/**
 * The browser has to ask for the same version this script wrote, so the path
 * is generated rather than typed in two places. Committed so a checkout builds
 * without running postinstall first.
 */
async function writeVersionModule() {
  await writeFile(
    versionModule,
    `// Generated by scripts/sync-ocr-assets.mjs. Do not edit.\n` +
      `//\n` +
      `// The onnxruntime build under public/ocr/wasm/<version>/. The version is\n` +
      `// in the path because the runtime's own filename never changes, which is\n` +
      `// what makes it safe to cache the file forever.\n` +
      `export const ORT_RUNTIME_VERSION = ${JSON.stringify(runtimeVersion)};\n`,
    "utf8",
  );
}

await verifyModels();
await copyRuntime();
await writeVersionModule();
console.log(
  `sync-ocr-assets: ${RUNTIME_FILES.length} runtime files copied to ` +
    `public/ocr/wasm/${runtimeVersion}/, ${MODEL_FILES.length} models verified.`,
);
